-- HSU-AUTO-SCHEDULER 초기 스키마 (sql/ddl_v3/schema.dbml 과 같은 내용)
--
-- 화면에 보이는 과목 정보(이름·학점·학년제한 …)는 lecture 에서 읽는다.
-- course 는 여러 학기에 걸쳐 "같은 과목"인지 판단하는 기준(과목코드 + 대표 이름)이다.
-- enum 값은 varchar + CHECK 로 둔다 (JPA @Enumerated(STRING) 로 바로 매핑).

-- 학기: '2026-2' 처럼 년도-학기를 그대로 키로 쓴다. term 1·2 정규, 3 여름, 4 겨울
create table semester (
    id         varchar(10) primary key,
    year       smallint    not null,
    term       smallint    not null,
    scraped_at timestamptz,                -- 종정시 수집 시각 (export 파일의 fetchedAt)

    constraint uk_semester unique (year, term),
    constraint chk_semester_term check (term between 1 and 4),
    constraint chk_semester_id check (id = year::text || '-' || term::text)
);

-- 전공: 종정시 전공코드(예: P012) 기준. 이름은 가장 최근 학기 값
create table major (
    id   bigint generated by default as identity primary key,
    code varchar(10)  not null,
    name varchar(100) not null,

    constraint uk_major_code unique (code)
);

-- 과목: 과목코드(예: P010182) 기준. name 은 대표 이름(분반들 중 가장 많이 쓰인 이름)
create table course (
    id   bigint generated by default as identity primary key,
    code varchar(20)  not null,
    name varchar(255) not null,

    constraint uk_course_code unique (code)
);

-- 학기별 전공-과목: 그 학기에 이 전공이 이 과목을 어떤 이수구분·몇 학년으로 여는지
-- grade 1~4, 0 = 전학년
create table major_course (
    id               bigint generated by default as identity primary key,
    semester_id      varchar(10) not null,
    major_id         bigint      not null,
    course_id        bigint      not null,
    requirement_type varchar(30) not null,
    grade            smallint    not null,

    constraint uk_major_course unique (semester_id, major_id, course_id),
    constraint fk_major_course_semester foreign key (semester_id) references semester (id) on delete cascade,
    constraint fk_major_course_major foreign key (major_id) references major (id) on delete restrict,
    constraint fk_major_course_course foreign key (course_id) references course (id) on delete restrict,
    constraint chk_major_course_requirement_type check (requirement_type in (
        'MAJOR_REQUIRED',            -- 전필
        'MAJOR_ELECTIVE',            -- 전선
        'MAJOR_BASIC',               -- 전기
        'GENERAL_REQUIRED',          -- 교필
        'REQUIRED_GENERAL_ELECTIVE', -- 선필교
        'GENERAL_ELECTIVE',          -- 일교
        'FREE_ELECTIVE',             -- 일선
        'MD_MAJOR_ELECTIVE',         -- MD전선
        'DOUBLE_MAJOR_ELECTIVE'      -- 복전선
    )),
    constraint chk_major_course_grade check (grade between 0 and 4)
);

create index idx_major_course_semester_course on major_course (semester_id, course_id);

-- 분반: 학기 + 과목 + 분반이 하나의 강의
create table lecture (
    id              bigint generated by default as identity primary key,
    semester_id     varchar(10)  not null,
    course_id       bigint       not null,
    section         varchar(5)   not null,            -- A, N, 7, @ ...
    name            varchar(255) not null,            -- 종정시에 보이는 분반의 과목명
    credit          smallint     not null,
    delivery_method varchar(20)  not null,            -- FACE_TO_FACE 대면수업 / ONLINE 온라인100% / BLENDED BL
    day_or_night    varchar(10)  not null,            -- DAY 주 / NIGHT 야 / BOTH 합
    professors      varchar(255) not null,            -- 쉼표 구분 원문, 미정은 '강사'
    online_minutes  smallint     not null default 0,  -- "온라인강좌 1.5시간" → 90
    grade_limit     smallint,                         -- 학년제한
    plan_code       varchar(30),                      -- 수업계획서 코드, 'X' 면 null
    remark          varchar(100),                     -- 비고 (수강인원, PF과목 …)
    classroom_raw   text         not null default '', -- 종정시 classroom 원문 (재파싱용)

    constraint uk_lecture unique (semester_id, course_id, section),
    constraint fk_lecture_semester foreign key (semester_id) references semester (id) on delete cascade,
    constraint fk_lecture_course foreign key (course_id) references course (id) on delete restrict,
    constraint chk_lecture_credit check (credit > 0),
    constraint chk_lecture_delivery_method check (delivery_method in ('FACE_TO_FACE', 'ONLINE', 'BLENDED')),
    constraint chk_lecture_day_or_night check (day_or_night in ('DAY', 'NIGHT', 'BOTH')),
    constraint chk_lecture_online_minutes check (online_minutes >= 0),
    constraint chk_lecture_grade_limit check (grade_limit between 1 and 4)
);

create index idx_lecture_course on lecture (course_id);

-- 오프라인 시간표: 시각은 자정부터의 분 (09:00 = 540)
create table offline_schedule (
    id         bigint generated by default as identity primary key,
    lecture_id bigint       not null,
    day        varchar(3)   not null,
    start_time smallint     not null,
    end_time   smallint     not null,
    place      varchar(100) not null,

    constraint uk_offline_schedule unique (lecture_id, day, start_time),
    constraint fk_offline_schedule_lecture foreign key (lecture_id) references lecture (id) on delete cascade,
    constraint chk_offline_schedule_day check (day in ('MON', 'TUE', 'WED', 'THU', 'FRI', 'SAT', 'SUN')),
    constraint chk_offline_schedule_time check (start_time >= 0 and end_time <= 1440 and start_time < end_time)
);
